import test from 'node:test';
import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { once } from 'node:events';
import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import sharp from 'sharp';
import { testPool } from './helpers/database.mjs';
import { migrate } from '../src/db/database.mjs';
import { AuthService } from '../src/auth/service.mjs';
import { createAuthServer } from '../src/auth/http.mjs';
import { ProfileService } from '../src/profile/service.mjs';
import { createApplicationRoutes } from '../src/dashboard/routes.mjs';
import { createProfileClient } from '../integrations/ruoyi-vue3/src/views/leet/profile-api.mjs';

test('RuoYi profile uploads raw images, rejects stale edits and revokes all admin sessions on password change', async t => {
  const {pool} = await testPool();
  const root = await mkdtemp(join(tmpdir(),'leet-profile-'));
  let server;
  t.after(async () => { if (server) { server.closeAllConnections(); await new Promise(resolve=>server.close(resolve)); } await pool.end(); await rm(root,{recursive:true,force:true}); });
  await migrate(pool);
  const auth = new AuthService(pool), profile = new ProfileService(pool,auth,root);
  const password = randomUUID(), replacement = randomUUID();
  await auth.bootstrap(password);
  const actor = await auth.login('CTL LEE',password), peer = await auth.login('CTL LEE',password);
  await auth.createEmployee({username:'profile-worker',realName:'Worker',password});
  const employee = await auth.login('profile-worker',password);
  server = createAuthServer({auth,publicOrigin:'https://warehouse.test',applicationRoutes:createApplicationRoutes({auth,profile})});
  server.listen(0,'127.0.0.1'); await once(server,'listening');
  const client = session => createProfileClient({request:(path,options)=>fetch('http://127.0.0.1:'+server.address().port+path,{...options,headers:{...options.headers,Origin:'https://warehouse.test',...(session && {Cookie:'__Host-warehouse_session='+session.token})}})});
  const api = client(actor), staff = client(employee);
  const initial = await api.get();
  await api.save('Administrator',initial.profileVersion);
  await assert.rejects(api.save('Stale name',initial.profileVersion),failure=>failure.code==='PROFILE_VERSION_CONFLICT');
  assert.equal((await api.get()).realName,'Administrator');
  const image = await sharp({create:{width:8,height:8,channels:3,background:'#245de9'}}).png().toBuffer();
  const file = new Blob([image],{type:'image/png'});
  await api.avatar(file);
  assert.equal((await api.get()).hasAvatar,true);
  assert.equal((await sharp((await profile.avatar(actor.token)).buffer).metadata()).format,'png');
  await assert.rejects(api.avatar(new Blob(['invalid'],{type:'image/png'})));
  await assert.rejects(staff.avatar(file),/ADMIN_REQUIRED/);
  await assert.rejects(staff.save('No access','1'),/ADMIN_REQUIRED/);
  await api.removeAvatar();
  assert.equal((await api.get()).hasAvatar,false);
  const wrong = await fetch('http://127.0.0.1:'+server.address().port+'/api/me/password',{method:'POST',headers:{Origin:'https://warehouse.test',Cookie:'__Host-warehouse_session='+actor.token,'X-CSRF-Token':actor.csrf,'Content-Type':'application/json'},body:JSON.stringify({oldPassword:randomUUID(),newPassword:replacement})});
  assert.equal(wrong.status,401);
  assert.equal((await wrong.json()).error,'INVALID_CREDENTIALS');
  assert.equal(wrong.headers.get('set-cookie'),null);
  await assert.rejects(api.password(randomUUID(),replacement),failure=>failure.code==='INVALID_CREDENTIALS');
  assert.equal((await api.get()).realName,'Administrator');
  await api.password(password,replacement);
  const revoked = await fetch('http://127.0.0.1:'+server.address().port+'/api/me/password',{method:'POST',headers:{Origin:'https://warehouse.test',Cookie:'__Host-warehouse_session='+actor.token,'X-CSRF-Token':actor.csrf,'Content-Type':'application/json'},body:JSON.stringify({oldPassword:password,newPassword:replacement})});
  assert.equal(revoked.status,401);
  assert.match(revoked.headers.get('set-cookie'),/Max-Age=0/);
  await assert.rejects(api.get(),/LOGIN_REQUIRED/);
  await assert.rejects(client(peer).get(),/LOGIN_REQUIRED/);
  await assert.rejects(auth.login('CTL LEE',password),failure=>failure.code==='INVALID_CREDENTIALS');
  const fresh = await auth.login('CTL LEE',replacement);
  assert.equal((await client(fresh).get()).realName,'Administrator');
  assert.equal((await staff.get()).username,'profile-worker');
});
