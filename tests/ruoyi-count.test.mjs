import test from 'node:test';
import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { once } from 'node:events';
import { testPool } from './helpers/database.mjs';
import { migrate } from '../src/db/database.mjs';
import { AuthService } from '../src/auth/service.mjs';
import { createAuthServer } from '../src/auth/http.mjs';
import { CatalogService, UNASSIGNED } from '../src/catalog/service.mjs';
import { createCatalogRoutes } from '../src/catalog/routes.mjs';
import { StockService } from '../src/stock/service.mjs';
import { CountService } from '../src/count/service.mjs';
import { createCountRoutes } from '../src/count/routes.mjs';
import { createCountClient } from '../integrations/ruoyi-vue3/src/views/leet/count-api.mjs';

test('RuoYi stocktake management fixes scopes and preserves stock through report lifecycle operations', async t => {
  const { pool } = await testPool();
  let server;
  t.after(async () => { if (server) { server.closeAllConnections(); await new Promise(resolve => server.close(resolve)); } await pool.end(); });
  await migrate(pool);
  const auth = new AuthService(pool), seed = new CatalogService(pool), catalog = new CatalogService(pool, auth), count = new CountService(pool, auth), stock = new StockService(pool, auth);
  const password = randomUUID();
  await auth.bootstrap(password);
  const admin = await auth.login('CTL LEE', password);
  await auth.createEmployee({ username: 'count-worker', realName: 'Count worker', password });
  const employee = await auth.login('count-worker', password);
  const category = await seed.addMaster('categories', { name: 'Count category' });
  const input = { name: 'Bolt A', categoryId: category.id, locationId: UNASSIGNED, individualCost: '1.25', minimumStock: 0, supplierIds: [] };
  const first = await seed.create(input);
  await seed.create({ ...input, name: 'Bolt B' });
  await stock.commit(admin.token, admin.csrf, { requestId: randomUUID(), kind: 'inbound', items: [{ productId: first.id, quantity: 5 }] });
  const before = await catalog.detail(first.id);
  server = createAuthServer({ auth, publicOrigin: 'https://warehouse.test', countRoutes: createCountRoutes({ count, auth }), catalogRoutes: createCatalogRoutes({ catalog, auth }) });
  server.listen(0, '127.0.0.1');
  await once(server, 'listening');
  const client = session => createCountClient({
    request: (path, options) => fetch('http://127.0.0.1:' + server.address().port + path, { ...options, headers: { ...options.headers, Origin: 'https://warehouse.test', ...(session && { Cookie: '__Host-warehouse_session=' + session.token }) } }),
  });
  const api = client(admin), staff = client(employee);
  const task = await api.publish({ title: 'Warehouse count', scope: 'category', scopeId: category.id });
  assert.equal(task.productCount, 2);
  await seed.create({ ...input, name: 'Added after publication' });
  const fixed = await api.task(task.id);
  assert.equal(fixed.items.length, 2);
  const copy = await api.publish({ title: 'Independent copy', scope: 'products', productIds: fixed.items.map(row => row.productId) });
  assert.notEqual(copy.id, task.id);
  await api.cancel(copy.id);
  assert.equal((await api.task(task.id)).task.status, 'pending');
  assert.equal((await api.task(copy.id)).task.status, 'cancelled');
  await api.cancel(copy.id, true);
  await assert.rejects(api.task(copy.id), error => error.code === 'TASK_NOT_FOUND_OR_CANCELLED');
  await assert.rejects(staff.publish({ title: 'Forbidden', scope: 'all' }), /ADMIN_REQUIRED/);
  await assert.rejects(staff.cancel(task.id), /ADMIN_REQUIRED/);
  await count.accept(employee.token, employee.csrf, task.id);
  const run = await count.begin(employee.token, employee.csrf, task.id);
  await count.connect(employee.token, employee.csrf, task.id, run);
  const submission = { ...run, requestId: randomUUID(), items: fixed.items.map(row => ({ productId: row.productId, quantity: row.productId === first.id ? 3 : 0 })) };
  const result = await count.submit(employee.token, employee.csrf, task.id, submission);
  assert.equal((await count.submit(employee.token, employee.csrf, task.id, submission)).reportId, result.reportId);
  await assert.rejects(api.cancel(task.id), error => error.code === 'TASK_ALREADY_COMPLETED');
  const activeTask = await api.publish({ title: 'Cancel active task', scope: 'all' });
  await count.accept(employee.token, employee.csrf, activeTask.id);
  const activeRun = await count.begin(employee.token, employee.csrf, activeTask.id);
  await count.connect(employee.token, employee.csrf, activeTask.id, activeRun);
  await api.cancel(activeTask.id);
  await assert.rejects(count.heartbeat(employee.token, employee.csrf, activeTask.id, activeRun), error => error.code === 'TASK_NOT_FOUND_OR_CANCELLED');
  const report = await api.report(result.reportId);
  const item = report.items.find(row => row.productId === first.id);
  assert.equal(item.systemQuantity, 5);
  assert.equal(item.actualQuantity, 3);
  assert.equal(item.difference, -2);
  await assert.rejects(api.reportAction('delete', [result.reportId]), error => error.code === 'REPORT_NOT_IN_TRASH');
  await assert.rejects(staff.reportAction('trash', [result.reportId]), /ADMIN_REQUIRED/);
  await api.reportAction('trash', [result.reportId]);
  assert.equal((await api.reports(false)).reports.length, 0);
  assert.equal((await api.reports(true)).reports.length, 1);
  await assert.rejects(staff.report(result.reportId), error => error.code === 'REPORT_NOT_FOUND');
  await api.reportAction('restore', [result.reportId]);
  assert.deepEqual((await api.report(result.reportId)).items, report.items);
  await api.reportAction('trash', [result.reportId]);
  await api.reportAction('delete', [result.reportId]);
  await assert.rejects(api.report(result.reportId), error => error.code === 'REPORT_NOT_FOUND');
  const after = await catalog.detail(first.id);
  assert.equal(after.quantity, before.quantity);
  assert.equal(after.inventoryVersion, before.inventoryVersion);
  await assert.rejects(client(null).tasks(), /LOGIN_REQUIRED/);
});
