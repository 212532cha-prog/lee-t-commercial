import test from 'node:test';
import assert from 'node:assert/strict';
import {randomUUID} from 'node:crypto';
import {once} from 'node:events';
import {mkdtemp,rm} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import sharp from 'sharp';
import jsQR from 'jsqr';
import {testPool} from './helpers/database.mjs';
import {workbookWithRows,productRow} from './helpers/product-workbook.mjs';
import {migrate} from '../src/db/database.mjs';
import {AuthService} from '../src/auth/service.mjs';
import {createAuthServer} from '../src/auth/http.mjs';
import {CatalogService,UNASSIGNED} from '../src/catalog/service.mjs';
import {PhotoStore} from '../src/catalog/files.mjs';
import {createCatalogRoutes} from '../src/catalog/routes.mjs';
import {StockService} from '../src/stock/service.mjs';
import {createProductAssetsClient,workbookType} from '../integrations/ruoyi-vue3/src/views/leet/product-assets-api.mjs';

test('RuoYi product assets preserve QR and inventory and require a matching atomic Excel preview',async t=>{
  const {pool}=await testPool(),root=await mkdtemp(join(tmpdir(),'leet-assets-'));
  let server;
  t.after(async()=>{if(server){server.closeAllConnections();await new Promise(resolve=>server.close(resolve));}await pool.end();await rm(root,{recursive:true,force:true});});
  await migrate(pool);
  const auth=new AuthService(pool),catalog=new CatalogService(pool),guarded=new CatalogService(pool,auth),photos=new PhotoStore(pool,root,auth),stock=new StockService(pool,auth);
  const password=randomUUID();await auth.bootstrap(password);
  const actor=await auth.login('CTL LEE',password),peer=await auth.login('CTL LEE',password);
  await auth.createEmployee({username:'asset-worker',realName:'Worker',password});const employee=await auth.login('asset-worker',password);
  const category=await catalog.addMaster('categories',{name:'Assets'}),input={name:'Existing product',categoryId:category.id,locationId:UNASSIGNED,individualCost:'1.25',minimumStock:0,supplierIds:[]};
  const first=await catalog.create(input);
  await stock.commit(actor.token,actor.csrf,{requestId:randomUUID(),kind:'inbound',items:[{productId:first.id,quantity:5}]});
  const before=await catalog.detail(first.id);
  server=createAuthServer({auth,publicOrigin:'https://warehouse.test',catalogRoutes:createCatalogRoutes({auth,catalog:guarded,photos})});
  server.listen(0,'127.0.0.1');await once(server,'listening');const base='http://127.0.0.1:'+server.address().port;
  const client=session=>createProductAssetsClient({request:(path,options)=>fetch(base+path,{...options,headers:{...options.headers,Origin:'https://warehouse.test',...(session&&{Cookie:'__Host-warehouse_session='+session.token})}})});
  const api=client(actor),staff=client(employee);
  const image=await sharp({create:{width:8,height:8,channels:3,background:'#245de9'}}).png().toBuffer();
  await api.photo(first.id,new Blob([image],{type:'image/png'}));assert.equal((await catalog.detail(first.id)).hasPhoto,true);
  assert.equal((await sharp((await photos.get(first.id)).buffer).metadata()).format,'png');
  await assert.rejects(staff.removePhoto(first.id),/ADMIN_REQUIRED/);
  await api.removePhoto(first.id);assert.equal((await catalog.detail(first.id)).hasPhoto,false);
  const response=await fetch(base+'/api/products/'+first.id+'/qr/download',{headers:{Cookie:'__Host-warehouse_session='+actor.token}});
  assert.equal(response.status,200);assert.match(response.headers.get('content-disposition'),/attachment/);
  const svg=await response.text(),raster=await sharp(Buffer.from(svg)).ensureAlpha().raw().toBuffer({resolveWithObject:true});
  assert.equal(jsQR(new Uint8ClampedArray(raster.data),raster.info.width,raster.info.height).data,before.qrToken);
  const invalid=new Blob([await workbookWithRows(productRow(2,'Invalid minimum',1,-1))],{type:workbookType});
  const rejected=await api.preview(category.id,invalid);assert.equal(rejected.previewToken,null);assert.equal(rejected.errors[0].error,'INVALID_MINIMUM');
  assert.equal((await catalog.list()).products.length,1);
  const file=new Blob([await workbookWithRows(productRow(2,'Excel product',3.25,2))],{type:workbookType});
  const preview=await api.preview(category.id,file);assert.ok(preview.previewToken);assert.equal(preview.rows[0].cost,'3.25');
  assert.equal((await catalog.list()).products.length,1);
  await assert.rejects(client(peer).commit(category.id,file,preview.previewToken),failure=>failure.code==='IMPORT_PREVIEW_REQUIRED');
  const changed=new Blob([await workbookWithRows(productRow(2,'Changed file',2,1))],{type:workbookType});
  await assert.rejects(api.commit(category.id,changed,preview.previewToken),failure=>failure.code==='IMPORT_PREVIEW_REQUIRED');
  const imported=await api.commit(category.id,file,preview.previewToken);assert.equal(imported.products.length,1);
  assert.equal((await catalog.detail(imported.products[0].id)).quantity,0);
  await assert.rejects(api.commit(category.id,file,preview.previewToken),failure=>failure.code==='IMPORT_ROWS_CHANGED');
  assert.equal((await catalog.list()).products.length,2);
  await assert.rejects(staff.preview(category.id,file),/ADMIN_REQUIRED/);
  await assert.rejects(client(null).photo(first.id,new Blob([image],{type:'image/png'})),/LOGIN_REQUIRED/);
  const after=await catalog.detail(first.id);assert.equal(after.quantity,before.quantity);assert.equal(after.inventoryVersion,before.inventoryVersion);assert.equal(after.qrToken,before.qrToken);
});
