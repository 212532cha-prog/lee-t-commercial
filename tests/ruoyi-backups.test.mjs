import test from 'node:test';
import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { once } from 'node:events';
import { mkdtemp, mkdir, rm, readFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { testPool } from './helpers/database.mjs';
import { migrate } from '../src/db/database.mjs';
import { AuthService } from '../src/auth/service.mjs';
import { createAuthServer } from '../src/auth/http.mjs';
import { BackupService } from '../src/backup/service.mjs';
import { createBackupRoutes } from '../src/backup/routes.mjs';
import { CatalogService, UNASSIGNED } from '../src/catalog/service.mjs';
import { StockService } from '../src/stock/service.mjs';
import { createBackupClient } from '../integrations/ruoyi-vue3/src/views/leet/backup-api.mjs';

test('RuoYi backup API preserves recovery protections, restrictions, upload verification and restored balances', async t => {
  const {pool} = await testPool();
  const root = await mkdtemp(join(tmpdir(),'leet-backups-')), dataDir=join(root,'data'), primary=join(root,'primary'), fallback=join(root,'fallback');
  await Promise.all([dataDir,primary,fallback].map(path=>mkdir(path)));
  let server, full=false;
  const auth = new AuthService(pool), backup = new BackupService(pool,auth,dataDir,{fault:async ({phase})=>{if(full && phase==='write') throw Object.assign(Error('full'),{code:'ENOSPC'});}});
  t.after(async()=>{if(server){server.closeAllConnections();await new Promise(resolve=>server.close(resolve));}await backup.waitForIdle();await pool.end();await rm(root,{recursive:true,force:true});});
  await migrate(pool);
  const password=randomUUID();await auth.bootstrap(password);
  let actor=await auth.login('CTL LEE',password);
  await auth.createEmployee({username:'backup-worker',realName:'Worker',password});
  const employee=await auth.login('backup-worker',password);
  const catalog=new CatalogService(pool), stock=new StockService(pool,auth);
  const category=await catalog.addMaster('categories',{name:'Backup category'});
  const product=await catalog.create({name:'Saved stock',categoryId:category.id,locationId:UNASSIGNED,individualCost:'1.25',minimumStock:0,supplierIds:[]});
  const move=quantity=>stock.commit(actor.token,actor.csrf,{requestId:randomUUID(),kind:'inbound',items:[{productId:product.id,quantity}]});
  await move(5);
  server=createAuthServer({auth,publicOrigin:'https://warehouse.test',backupRoutes:createBackupRoutes({backup})});
  server.listen(0,'127.0.0.1');await once(server,'listening');
  const client=session=>createBackupClient({request:(path,options)=>fetch('http://127.0.0.1:'+server.address().port+path,{...options,headers:{...options.headers,Origin:'https://warehouse.test',...(session && {Cookie:'__Host-warehouse_session='+session.token})}})});
  let api=client(actor);
  const initial=await api.list();
  await api.configure({path1:primary,path2:fallback,expectedRevision:initial.config.revision});
  await assert.rejects(api.configure({path1:primary,path2:fallback,expectedRevision:initial.config.revision}),failure=>failure.code==='BACKUP_CONFIG_VERSION_CONFLICT');
  const saved=await api.create();assert.equal(saved.verified,true);
  await assert.rejects(api.remove(saved.id),failure=>failure.code==='LAST_VALID_BACKUP');
  const file=await readFile(join(primary,saved.id+'.whb'));
  const upload=await api.upload(new Blob([file],{type:'application/octet-stream'}));assert.equal(upload.verified,true);
  await assert.rejects(api.upload(new Blob(['invalid'],{type:'application/octet-stream'})));
  await api.maintenance(true);
  assert.equal((await api.list()).state.maintenance,true);
  await assert.rejects(move(1),failure=>failure.code==='MAINTENANCE');
  await api.maintenance(false);
  full=true;
  await assert.rejects(api.create(),failure=>failure.code==='BACKUP_FAILED');
  assert.equal((await api.list()).state.admin_backup_required,true);
  await assert.rejects(move(1),failure=>failure.code==='ADMIN_BACKUP_REQUIRED');
  full=false;await api.create();
  assert.equal((await api.list()).state.admin_backup_required,false);
  await move(3);assert.equal((await catalog.detail(product.id)).quantity,8);
  await api.restore(upload.id,true);
  await assert.rejects(api.list(),/LOGIN_REQUIRED/);
  actor=await auth.login('CTL LEE',password);api=client(actor);
  assert.equal((await catalog.detail(product.id)).quantity,5);
  assert.equal((await api.list()).state.maintenance,false);
  assert.ok((await api.list()).backups.some(row=>row.kind==='pre_restore'));
  await api.cleanUploads();assert.equal(Number((await pool.query('SELECT count(*) AS count FROM backup_uploads')).rows[0].count),0);
  await assert.rejects(client(employee).list(),/LOGIN_REQUIRED/);
  const freshEmployee=await auth.login('backup-worker',password);
  await assert.rejects(client(freshEmployee).list(),/ADMIN_REQUIRED/);
});
