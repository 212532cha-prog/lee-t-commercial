import test from 'node:test';
import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { once } from 'node:events';
import { testPool } from './helpers/database.mjs';
import { migrate } from '../src/db/database.mjs';
import { AuthService } from '../src/auth/service.mjs';
import { createAuthServer } from '../src/auth/http.mjs';
import { CatalogService, UNASSIGNED } from '../src/catalog/service.mjs';
import { StockService } from '../src/stock/service.mjs';
import { DashboardService } from '../src/dashboard/service.mjs';
import { createApplicationRoutes } from '../src/dashboard/routes.mjs';
import { createDashboardClient, formatCost } from '../integrations/ruoyi-vue3/src/views/leet/dashboard-api.mjs';

test('RuoYi costs paginate without rounding and reminder tokens reject later negative crossings', async t => {
  const { pool } = await testPool();
  let server;
  t.after(async () => { if (server) { server.closeAllConnections(); await new Promise(resolve => server.close(resolve)); } await pool.end(); });
  await migrate(pool);
  const auth = new AuthService(pool), seed = new CatalogService(pool), stock = new StockService(pool, auth), dashboard = new DashboardService(pool, auth);
  const password = randomUUID();
  await auth.bootstrap(password);
  const actor = await auth.login('CTL LEE', password);
  await auth.createEmployee({ username: 'cost-worker', realName: 'Worker', password });
  const employee = await auth.login('cost-worker', password);
  const category = await seed.addMaster('categories', { name: 'Costs' });
  const input = { name: 'Exact cost', categoryId: category.id, locationId: UNASSIGNED, individualCost: '0.12', minimumStock: 0, supplierIds: [] };
  const first = await seed.create(input);
  for (let n = 0; n < 100; n++) await seed.create({ ...input, name: 'Cost ' + n });
  const move = (kind, quantity) => stock.commit(actor.token, actor.csrf, { requestId: randomUUID(), kind, items: [{ productId: first.id, quantity }] });
  await move('outbound', 3);
  server = createAuthServer({ auth, publicOrigin: 'https://warehouse.test', applicationRoutes: createApplicationRoutes({ auth, dashboard }) });
  server.listen(0, '127.0.0.1'); await once(server, 'listening');
  const client = session => createDashboardClient({ request: (path, options) => fetch('http://127.0.0.1:' + server.address().port + path, { ...options, headers: { ...options.headers, Origin: 'https://warehouse.test', ...(session && { Cookie: '__Host-warehouse_session=' + session.token }) } }) });
  const api = client(actor), staff = client(employee);
  const page = await api.costs(), last = await api.costs(page.nextCursor);
  assert.equal(page.products.length, 100);
  assert.equal(last.products.length, 1);
  assert.equal(last.nextCursor, null);
  assert.equal(new Set([...page.products, ...last.products].map(row => row.id)).size, 101);
  const cost = [...page.products, ...last.products].find(row => row.id === first.id);
  assert.equal(cost.quantity, -3);
  assert.equal(formatCost(cost.individualCost), 'RM 0.12');
  assert.equal(formatCost(cost.value), 'RM -0.36');
  assert.equal(formatCost('12345678901234567890.123456'), 'RM 12,345,678,901,234,567,890.123456');
  assert.equal(formatCost('0'), 'RM 0.00');
  assert.equal(formatCost('<script>'), '—');
  let reminder = (await dashboard.get(actor.token)).negative[0];
  const oldToken = reminder.notificationToken;
  await api.markRead(first.id, oldToken);
  assert.equal((await dashboard.get(actor.token)).negative[0].read, true);
  await move('inbound', 3); await move('outbound', 1);
  reminder = (await dashboard.get(actor.token)).negative[0];
  assert.notEqual(reminder.notificationToken, oldToken);
  await assert.rejects(api.markRead(first.id, oldToken), failure => failure.code === 'NOTIFICATION_CHANGED');
  assert.equal((await dashboard.get(actor.token)).negative[0].read, false);
  await assert.rejects(staff.costs(), /ADMIN_REQUIRED/);
  await assert.rejects(staff.markRead(first.id, reminder.notificationToken), /ADMIN_REQUIRED/);
  await assert.rejects(client(null).costs(), /LOGIN_REQUIRED/);
  await api.markRead(first.id, reminder.notificationToken);
  assert.equal((await seed.detail(first.id)).quantity, -1);
});
