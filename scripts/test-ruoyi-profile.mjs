import assert from 'node:assert/strict';
import sharp from 'sharp';
import { ProfileService } from '../src/profile/service.mjs';
import { createServer, request } from 'node:http';
import { once } from 'node:events';
import { randomUUID } from 'node:crypto';
import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { testPool } from '../tests/helpers/database.mjs';
import { launchBrowser } from '../tests/helpers/browser.mjs';
import { migrate } from '../src/db/database.mjs';
import { AuthService } from '../src/auth/service.mjs';
import { createAuthServer } from '../src/auth/http.mjs';
import { CatalogService, UNASSIGNED } from '../src/catalog/service.mjs';
import { PhotoStore } from '../src/catalog/files.mjs';
import { createCatalogRoutes } from '../src/catalog/routes.mjs';
import { StockService } from '../src/stock/service.mjs';
import { DashboardService } from '../src/dashboard/service.mjs';
import { createApplicationRoutes } from '../src/dashboard/routes.mjs';

if (!process.argv[2]) throw Error('Provide the built RuoYi directory.');
const { pool } = await testPool();
const directory = await mkdtemp(join(tmpdir(), 'leet-ruoyi-browser-'));
let server, proxy, browser;
try {
  await migrate(pool);
  const auth = new AuthService(pool), catalog = new CatalogService(pool, auth), seed = new CatalogService(pool);
  const password = randomUUID();
  await auth.bootstrap(password);
  await auth.createEmployee({ username: 'staff', realName: 'Count worker', password });
  const category = await seed.addMaster('categories', { name: 'Fasteners' });
  const input = { name: 'Bolt', categoryId: category.id, locationId: UNASSIGNED, individualCost: '1.25', minimumStock: 2, supplierIds: [] };
  const actor = await auth.login('CTL LEE', password);
  const first = await seed.create({ ...input, name: 'Bolt A' });
  await seed.create({ ...input, name: 'Bolt B' });
  const stock = new StockService(pool, auth), profile = new ProfileService(pool,auth,directory);
  await stock.commit(actor.token, actor.csrf, { requestId: randomUUID(), kind: 'inbound', items: [{ productId: first.id, quantity: 5 }] });
  const before = await catalog.detail(first.id);
  server = createAuthServer({
    auth, publicOrigin: 'https://warehouse.test', ruoyiAdminDirectory: resolve(process.argv[2]),
    catalogRoutes: createCatalogRoutes({ auth, catalog, photos: new PhotoStore(pool, directory, auth) }),
    applicationRoutes: createApplicationRoutes({ auth, dashboard: new DashboardService(pool, auth), profile }),
  });
  server.listen(0, '127.0.0.1');
  await once(server, 'listening');
  let base;
  // Localhost UI transport only. Production TLS validation is covered by the mandatory TLS suite.
  proxy = createServer((req, res) => {
    const headers = { ...req.headers };
    if (headers.origin === base) headers.origin = 'https://warehouse.test';
    const upstream = request({ host: '127.0.0.1', port: server.address().port, path: req.url, method: req.method, headers }, response => {
      res.writeHead(response.statusCode, response.headers);
      response.pipe(res);
      res.on('close', () => response.destroy());
    });
    upstream.on('error', () => { if (!res.headersSent) res.writeHead(502); res.end(); });
    req.pipe(upstream);
  });
  proxy.listen(0, '127.0.0.1');
  await once(proxy, 'listening');
  base = 'http://localhost:' + proxy.address().port;
  browser = await launchBrowser();
  const errors = [];
  const page = await browser.browser.newPage({ viewport: { width: 1440, height: 1000 } });
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(base + '/admin/');
  const login = page.locator('.sign-in-form');
  await login.locator('input[type=text]').fill('CTL LEE');
  await login.locator('input[type=password]').fill(randomUUID());
  await login.getByRole('button', { name: 'Sign in', exact: true }).click();
  await page.getByText('The username or password is incorrect, or the account is inactive.', { exact: true }).waitFor();
  assert.equal(await login.locator('input[type=password]').inputValue(), '');
  await login.locator('input[type=password]').fill(password);
  await login.getByRole('button', { name: 'Sign in', exact: true }).click();
  await page.getByRole('heading', { name: 'Warehouse overview', exact: true }).waitFor();
  await page.getByRole('menuitem',{name:'My account',exact:true}).click();
  const displayName = page.getByRole('textbox',{name:'Display name',exact:true});
  await displayName.fill('Administrator');
  await page.getByRole('button',{name:'Save profile',exact:true}).click();
  await page.getByText('Profile saved.',{exact:true}).waitFor();
  const current = (await profile.get(actor.token)).user;
  await profile.save(actor.token,actor.csrf,{realName:'Administrator updated',expectedVersion:current.profileVersion});
  await displayName.fill('Stale name');
  await page.getByRole('button',{name:'Save profile',exact:true}).click();
  await page.getByText('Your profile changed on another device. Refresh the profile before editing again.',{exact:true}).waitFor();
  assert.equal((await profile.get(actor.token)).user.realName,'Administrator updated');
  const refreshed = page.waitForResponse(r=>r.url()===base+'/api/profile' && r.request().method()==='GET');
  await page.getByRole('button',{name:'Refresh profile',exact:true}).click();
  await refreshed;
  for (let attempt=0; attempt<50 && await displayName.inputValue() !== 'Administrator updated'; attempt++) await new Promise(resolve=>setTimeout(resolve,100));
  assert.equal(await displayName.inputValue(),'Administrator updated');
  await displayName.fill('Administrator');
  await page.getByRole('button',{name:'Save profile',exact:true}).click();
  await page.getByText('Profile saved.',{exact:true}).waitFor();
  const image = await sharp({create:{width:16,height:16,channels:3,background:'#245de9'}}).png().toBuffer();
  const picker = page.getByLabel('Choose avatar',{exact:true});
  await picker.setInputFiles({name:'invalid.txt',mimeType:'text/plain',buffer:Buffer.from('invalid')});
  await page.getByText('Choose a JPG or PNG image up to 5 MB.',{exact:true}).waitFor();
  assert.equal(await page.getByRole('button',{name:'Upload avatar',exact:true}).isDisabled(),true);
  await picker.setInputFiles({name:'avatar.png',mimeType:'image/png',buffer:image});
  await page.getByRole('button',{name:'Upload avatar',exact:true}).click();
  await page.getByText('Avatar updated.',{exact:true}).waitFor();
  const avatar = page.getByRole('img',{name:'Administrator avatar',exact:true});
  await avatar.waitFor();
  await avatar.evaluate(image=>image.decode());
  assert.equal(await avatar.evaluate(image=>image.complete && image.naturalWidth>0),true);
  assert.equal((await profile.get(actor.token)).user.hasAvatar,true);
  await page.getByRole('button',{name:'Remove avatar',exact:true}).click();
  await page.getByRole('dialog',{name:'Confirm avatar removal',exact:true}).getByRole('button',{name:'OK',exact:true}).click();
  await page.getByText('Avatar removed.',{exact:true}).waitFor();
  assert.equal((await profile.get(actor.token)).user.hasAvatar,false);
  const replacement = randomUUID();
  const oldField = page.getByLabel('Current password',{exact:true}), newField = page.getByLabel('New password',{exact:true}), confirmation = page.getByLabel('Confirm new password',{exact:true});
  await oldField.fill(password); await newField.fill(replacement); await confirmation.fill(randomUUID());
  await page.getByRole('button',{name:'Change password',exact:true}).click();
  await page.getByText('The new passwords do not match.',{exact:true}).waitFor();
  await oldField.fill(randomUUID()); await confirmation.fill(replacement);
  await page.getByRole('button',{name:'Change password',exact:true}).click();
  await page.getByText('The current password is incorrect.',{exact:true}).waitFor();
  for (const field of [oldField,newField,confirmation]) assert.equal(await field.inputValue(),'');
  await oldField.fill(password); await newField.fill(replacement); await confirmation.fill(replacement);
  await page.getByRole('button',{name:'Change password',exact:true}).click();
  await login.locator('input[type=password]').waitFor();
  await assert.rejects(auth.authorize(actor.token),failure=>failure.status===401);
  await login.locator('input[type=password]').fill(password);
  await login.getByRole('button',{name:'Sign in',exact:true}).click();
  await page.getByText('The username or password is incorrect, or the account is inactive.',{exact:true}).waitFor();
  await login.locator('input[type=password]').fill(replacement);
  await login.getByRole('button',{name:'Sign in',exact:true}).click();
  await page.getByRole('heading',{name:'Warehouse overview',exact:true}).waitFor();
  await page.getByRole('menuitem',{name:'My account',exact:true}).click();
  await displayName.waitFor(); assert.equal(await displayName.inputValue(),'Administrator');
  assert.equal((await catalog.detail(first.id)).quantity,before.quantity);
  assert.equal((await catalog.detail(first.id)).inventoryVersion,before.inventoryVersion);
  assert.deepEqual(errors,[]);
  console.log('Built RuoYi profile: stale edit rejection, validated avatar upload/removal, password confirmation, session revocation and fresh sign-in passed.');
} finally {
  if (browser) { await browser.browser.close(); await browser.cleanup(); }
  for (const instance of [proxy,server]) if (instance) { instance.closeAllConnections(); await new Promise(resolve=>instance.close(resolve)); }
  await pool.end(); await rm(directory,{recursive:true,force:true});
}
