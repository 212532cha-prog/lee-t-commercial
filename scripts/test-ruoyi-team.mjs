import assert from 'node:assert/strict';
import { createServer, request } from 'node:http';
import { once } from 'node:events';
import { randomUUID } from 'node:crypto';
import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import sharp from 'sharp';
import jsQR from 'jsqr';
import { testPool } from '../tests/helpers/database.mjs';
import { launchBrowser } from '../tests/helpers/browser.mjs';
import { migrate } from '../src/db/database.mjs';
import { AuthService } from '../src/auth/service.mjs';
import { createAuthServer } from '../src/auth/http.mjs';
import { EmployeePairing } from '../src/commercial/employee-pairing.mjs';
import { DashboardService } from '../src/dashboard/service.mjs';
import { createApplicationRoutes } from '../src/dashboard/routes.mjs';
import { parsePairingFragment } from '../public/app/pairing.js';

if (!process.argv[2]) throw Error('Provide the built RuoYi directory.');
const { pool } = await testPool();
const directory = await mkdtemp(join(tmpdir(), 'leet-ruoyi-team-browser-'));
let server, proxy, browser;
try {
  await migrate(pool);
  const pairing = new EmployeePairing({ origin: 'https://warehouse.test', serverId: randomUUID(), certificateFingerprint: 'ab'.repeat(32) });
  const auth = new AuthService(pool, { pairing });
  const password = randomUUID(), employeePassword = randomUUID(), resetPassword = randomUUID();
  await auth.bootstrap(password);
  const administrator = await auth.login('CTL LEE', password);
  server = createAuthServer({
    auth, publicOrigin: pairing.origin, ruoyiAdminDirectory: resolve(process.argv[2]),
    applicationRoutes: createApplicationRoutes({ auth, dashboard: new DashboardService(pool, auth) }),
  });
  server.listen(0, '127.0.0.1');
  await once(server, 'listening');
  let base;
  // Localhost UI transport only. Mandatory TLS tests validate the production certificate rules.
  proxy = createServer((req, res) => {
    const headers = { ...req.headers };
    if (headers.origin === base) headers.origin = pairing.origin;
    const upstream = request({ host: '127.0.0.1', port: server.address().port, path: req.url, method: req.method, headers }, response => {
      res.writeHead(response.statusCode, response.headers);
      response.pipe(res);
      res.on('close', () => response.destroy());
    });
    upstream.on('error', () => { if (!res.headersSent) res.writeHead(502); res.end(); });
    req.pipe(upstream);
  });
  proxy.listen(0, '127.0.0.1');
  await once(proxy, 'listening');
  base = 'http://localhost:' + proxy.address().port;
  browser = await launchBrowser();
  const errors = [];
  const page = await browser.browser.newPage({ viewport: { width: 1440, height: 1000 } });
  page.on('pageerror', failure => errors.push(failure.message));
  await page.goto(base);
  await page.locator('#username').fill('CTL LEE');
  await page.locator('#password').fill(password);
  await page.locator('#login button').click();
  await page.locator('.workspace').waitFor();
  await page.goto(base + '/admin/');
  await page.getByRole('menuitem', { name: 'Employees and devices', exact: true }).click();
  await page.getByRole('button', { name: 'Add employee', exact: true }).click();
  const create = page.getByRole('dialog', { name: 'Add employee', exact: true });
  await create.getByRole('textbox').nth(0).fill('Browser worker');
  await create.getByRole('textbox').nth(1).fill('browser-worker');
  await create.locator('input[type=password]').nth(0).fill(employeePassword);
  await create.locator('input[type=password]').nth(1).fill(randomUUID());
  assert.equal(await create.getByRole('button', { name: 'Save employee', exact: true }).isDisabled(), true);
  await create.locator('input[type=password]').nth(1).fill(employeePassword);
  await create.getByRole('button', { name: 'Save employee', exact: true }).click();
  const row = page.locator('.el-table__row').filter({ hasText: 'browser-worker' });
  await row.getByRole('button', { name: 'Edit employee', exact: true }).click();
  const editor = page.getByRole('dialog', { name: 'Edit employee', exact: true });
  const employee = (await auth.employees()).find(person => person.username === 'browser-worker');
  await auth.editEmployee(employee.id, { username: employee.username, realName: 'Changed elsewhere', expectedVersion: employee.profileVersion }, { raw: administrator.token, csrf: administrator.csrf });
  await editor.getByRole('textbox').first().fill('Stale employee change');
  await editor.getByRole('button', { name: 'Save employee', exact: true }).click();
  await editor.getByText('Another device changed this employee.', { exact: false }).waitFor();
  assert.equal((await auth.employees()).find(person => person.id === employee.id).realName, 'Changed elsewhere');
  await editor.getByRole('button', { name: 'Cancel', exact: true }).click();
  await page.getByRole('button', { name: 'Refresh employees', exact: true }).click();
  await row.getByRole('button', { name: 'Pairing QR', exact: true }).click();
  const qrDialog = page.getByRole('dialog', { name: 'Employee pairing QR', exact: true });
  const image = qrDialog.getByRole('img', { name: 'Employee pairing QR', exact: true });
  await image.waitFor();
  const src = await image.getAttribute('src');
  assert.ok(src.startsWith('blob:'));
  await image.evaluate(element => element.decode());
  const bytes = await image.screenshot();
  const raw = await sharp(bytes).ensureAlpha().raw().toBuffer({ resolveWithObject: true });
  const decoded = jsQR(new Uint8ClampedArray(raw.data), raw.info.width, raw.info.height);
  assert.ok(decoded);
  const invitation = parsePairingFragment(new URL(decoded.data).hash);
  const first = await auth.login(employee.username, employeePassword, { invitation });
  await qrDialog.getByRole('button', { name: 'Close pairing QR', exact: true }).click();
  await row.getByRole('button', { name: 'Pairing QR', exact: true }).click();
  await page.getByText('This employee already has a paired device. Unbind it before pairing a replacement.', { exact: true }).waitFor();
  await row.getByRole('button', { name: 'Force sign-out', exact: true }).click();
  await page.getByRole('dialog', { name: 'Confirm employee action', exact: true }).getByRole('button', { name: 'OK', exact: true }).click();
  await page.getByText('Employee signed out.', { exact: true }).waitFor();
  await assert.rejects(auth.authorize(first.token), failure => failure.status === 401);
  const second = await auth.login(employee.username, employeePassword, { device: first.deviceToken });
  await row.getByRole('button', { name: 'Reset password', exact: true }).click();
  const reset = page.getByRole('dialog', { name: 'Reset employee password', exact: true });
  await reset.locator('input[type=password]').nth(0).fill(resetPassword);
  await reset.locator('input[type=password]').nth(1).fill(resetPassword);
  await reset.getByRole('button', { name: 'Save employee', exact: true }).click();
  await page.getByText('Password reset. The employee must sign in again.', { exact: true }).waitFor();
  await assert.rejects(auth.authorize(second.token), failure => failure.status === 401);
  await assert.rejects(auth.login(employee.username, employeePassword, { device: first.deviceToken }), failure => failure.code === 'INVALID_CREDENTIALS');
  const third = await auth.login(employee.username, resetPassword, { device: first.deviceToken });
  await row.getByRole('button', { name: 'Unbind device', exact: true }).click();
  await page.getByRole('dialog', { name: 'Confirm employee action', exact: true }).getByRole('button', { name: 'OK', exact: true }).click();
  await page.getByText('Device unbound.', { exact: true }).waitFor();
  await assert.rejects(auth.authorize(third.token), failure => failure.status === 401);
  assert.equal(Number((await pool.query('SELECT count(*) FROM employee_device_bindings WHERE user_id=$1', [employee.id])).rows[0].count), 0);
  await row.getByRole('button', { name: 'Deactivate', exact: true }).click();
  await page.getByRole('dialog', { name: 'Confirm employee action', exact: true }).getByRole('button', { name: 'OK', exact: true }).click();
  await row.getByText('Inactive', { exact: true }).waitFor();
  assert.equal((await auth.employees()).find(person => person.id === employee.id).active, false);
  assert.equal(await row.getByRole('button', { name: 'Pairing QR', exact: true }).isDisabled(), true);
  await page.waitForFunction(() => [...globalThis.document.querySelectorAll('.el-overlay')].every(element => element.getClientRects().length === 0));
  await page.screenshot({ path: process.argv[3] || join(directory, 'team.png'), fullPage: true });
  const otherPassword = randomUUID();
  const other = await auth.createEmployee({ username: 'browser-other', realName: 'Other worker', password: otherPassword });
  const otherInvite = await pairing.manage(auth, { raw: administrator.token, csrf: administrator.csrf }, other.id, 'invite');
  const staff = await browser.browser.newPage();
  await staff.goto(base + '/#pairing=' + encodeURIComponent(JSON.stringify(otherInvite)));
  await staff.locator('#username').fill('browser-other');
  await staff.locator('#password').fill(otherPassword);
  await staff.locator('#login button').click();
  await staff.locator('.workspace').waitFor();
  await staff.goto(base + '/admin/');
  await staff.getByText('An Administrator account is required.', { exact: true }).waitFor();
  assert.equal(await staff.getByRole('menuitem', { name: 'Employees and devices', exact: true }).count(), 0);
  assert.deepEqual(errors, []);
  console.log('Built RuoYi team: employee creation, profile conflict, QR enrollment, session revocation, password reset, unbinding, deactivation and employee denial passed.');
} finally {
  if (browser) { await browser.browser.close(); await browser.cleanup(); }
  for (const instance of [proxy, server]) if (instance) { instance.closeAllConnections(); await new Promise(resolve => instance.close(resolve)); }
  await pool.end();
  await rm(directory, { recursive: true, force: true });
}
