import assert from 'node:assert/strict';
import sharp from 'sharp';
import jsQR from 'jsqr';
import { readSheet } from 'read-excel-file/node';
import { workbookWithRows,productRow } from '../tests/helpers/product-workbook.mjs';
import { createServer, request } from 'node:http';
import { once } from 'node:events';
import { randomUUID } from 'node:crypto';
import { mkdtemp, rm, readFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { testPool } from '../tests/helpers/database.mjs';
import { launchBrowser } from '../tests/helpers/browser.mjs';
import { migrate } from '../src/db/database.mjs';
import { AuthService } from '../src/auth/service.mjs';
import { createAuthServer } from '../src/auth/http.mjs';
import { CatalogService, UNASSIGNED } from '../src/catalog/service.mjs';
import { PhotoStore } from '../src/catalog/files.mjs';
import { createCatalogRoutes } from '../src/catalog/routes.mjs';
import { StockService } from '../src/stock/service.mjs';
import { DashboardService } from '../src/dashboard/service.mjs';
import { createApplicationRoutes } from '../src/dashboard/routes.mjs';

if (!process.argv[2]) throw Error('Provide the built RuoYi directory.');
const { pool } = await testPool();
const directory = await mkdtemp(join(tmpdir(), 'leet-ruoyi-browser-'));
let server, proxy, browser;
try {
  await migrate(pool);
  const auth = new AuthService(pool), catalog = new CatalogService(pool, auth), seed = new CatalogService(pool);
  const password = randomUUID();
  await auth.bootstrap(password);
  await auth.createEmployee({ username: 'staff', realName: 'Count worker', password });
  const category = await seed.addMaster('categories', { name: 'Fasteners' });
  const input = { name: 'Bolt', categoryId: category.id, locationId: UNASSIGNED, individualCost: '1.25', minimumStock: 2, supplierIds: [] };
  const actor = await auth.login('CTL LEE', password);
  const first = await seed.create({ ...input, name: 'Bolt A' });
  await seed.create({ ...input, name: 'Bolt B' });
  const stock = new StockService(pool, auth);
  await stock.commit(actor.token, actor.csrf, { requestId: randomUUID(), kind: 'inbound', items: [{ productId: first.id, quantity: 5 }] });
  const before = await catalog.detail(first.id);
  server = createAuthServer({
    auth, publicOrigin: 'https://warehouse.test', ruoyiAdminDirectory: resolve(process.argv[2]),
    catalogRoutes: createCatalogRoutes({ auth, catalog, photos: new PhotoStore(pool, directory, auth) }),
    applicationRoutes: createApplicationRoutes({ auth, dashboard: new DashboardService(pool, auth) }),
  });
  server.listen(0, '127.0.0.1');
  await once(server, 'listening');
  let base;
  // Localhost UI transport only. Production TLS validation is covered by the mandatory TLS suite.
  proxy = createServer((req, res) => {
    const headers = { ...req.headers };
    if (headers.origin === base) headers.origin = 'https://warehouse.test';
    const upstream = request({ host: '127.0.0.1', port: server.address().port, path: req.url, method: req.method, headers }, response => {
      res.writeHead(response.statusCode, response.headers);
      response.pipe(res);
      res.on('close', () => response.destroy());
    });
    upstream.on('error', () => { if (!res.headersSent) res.writeHead(502); res.end(); });
    req.pipe(upstream);
  });
  proxy.listen(0, '127.0.0.1');
  await once(proxy, 'listening');
  base = 'http://localhost:' + proxy.address().port;
  browser = await launchBrowser();
  const errors = [];
  const page = await browser.browser.newPage({ viewport: { width: 1440, height: 1000 } });
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(base + '/admin/');
  const login = page.locator('.sign-in-form');
  await login.locator('input[type=text]').fill('CTL LEE');
  await login.locator('input[type=password]').fill(randomUUID());
  await login.getByRole('button', { name: 'Sign in', exact: true }).click();
  await page.getByText('The username or password is incorrect, or the account is inactive.', { exact: true }).waitFor();
  assert.equal(await login.locator('input[type=password]').inputValue(), '');
  await login.locator('input[type=password]').fill(password);
  await login.getByRole('button', { name: 'Sign in', exact: true }).click();
  await page.getByRole('heading', { name: 'Warehouse overview', exact: true }).waitFor();
  await page.getByRole('menuitem',{name:'Products',exact:true}).click();
  const row=page.locator('.el-table__row').filter({hasText:'Bolt A'});
  await row.getByRole('button',{name:'Details',exact:true}).click();
  const details=page.getByRole('dialog',{name:'Product details',exact:true});
  const photoPicker=details.getByLabel('Choose product photo',{exact:true});
  await photoPicker.setInputFiles({name:'invalid.txt',mimeType:'text/plain',buffer:Buffer.from('invalid')});
  await details.getByText('Choose a JPG or PNG image up to 5 MB.',{exact:true}).waitFor();
  assert.equal(await details.getByRole('button',{name:'Upload photo',exact:true}).isDisabled(),true);
  const image=await sharp({create:{width:16,height:16,channels:3,background:'#245de9'}}).png().toBuffer();
  await photoPicker.setInputFiles({name:'photo.png',mimeType:'image/png',buffer:image});
  await details.getByRole('button',{name:'Upload photo',exact:true}).click();
  const photo=details.getByRole('img',{name:'Photo of Bolt A',exact:true});await photo.waitFor();await photo.evaluate(image=>image.decode());
  assert.ok(await photo.evaluate(image=>image.naturalWidth>0));
  assert.equal((await catalog.detail(first.id)).hasPhoto,true);
  const download=page.waitForEvent('download');await details.getByRole('link',{name:'Download QR',exact:true}).click();
  const file=await download,svgPath=join(directory,'qr.svg');await file.saveAs(svgPath);assert.match(file.suggestedFilename(),/\.svg$/);
  const raster=await sharp(await readFile(svgPath)).ensureAlpha().raw().toBuffer({resolveWithObject:true});
  assert.equal(jsQR(new Uint8ClampedArray(raster.data),raster.info.width,raster.info.height).data,before.qrToken);
  const printed=page.waitForEvent('popup');await details.getByRole('link',{name:'Print QR',exact:true}).click();
  const label=await printed;await label.getByRole('heading',{name:'Bolt A',exact:true}).waitFor();assert.equal(await label.locator('svg').count(),1);await label.close();
  await details.getByRole('button',{name:'Remove photo',exact:true}).click();
  await page.getByRole('dialog',{name:'Confirm photo removal',exact:true}).getByRole('button',{name:'OK',exact:true}).click();
  await photo.waitFor({state:'hidden'});assert.equal((await catalog.detail(first.id)).hasPhoto,false);
  await details.locator('.el-dialog__headerbtn').click();await details.waitFor({state:'hidden'});
  const second=(await catalog.list()).products.find(product=>product.id!==first.id);
  const firstCheck=page.getByLabel('Select QR label for '+first.productCode,{exact:true}),secondCheck=page.getByLabel('Select QR label for '+second.productCode,{exact:true});
  const print=page.getByRole('link',{name:/Print selected QR/});assert.equal(await print.isDisabled(),true);
  await firstCheck.check();await secondCheck.check();
  const batchPopup=page.waitForEvent('popup');await print.click();const batch=await batchPopup;
  await batch.locator('.qr-label').nth(1).waitFor();assert.equal(await batch.locator('.qr-label').count(),2);
  await batch.getByText('Bolt A',{exact:true}).waitFor();await batch.getByText('Bolt B',{exact:true}).waitFor();await batch.close();
  await firstCheck.uncheck();await secondCheck.uncheck();assert.equal(await print.isDisabled(),true);
  await page.getByRole('button',{name:'Import products',exact:true}).click();
  const importer=page.getByRole('dialog',{name:'Import products',exact:true});
  const templateDownload=page.waitForEvent('download');await importer.getByRole('link',{name:'Download Excel template',exact:true}).click();
  const template=await templateDownload,templatePath=join(directory,'template.xlsx');await template.saveAs(templatePath);
  assert.deepEqual(await readSheet(await readFile(templatePath),'Products'),[['Name','Unit cost (RM)','Minimum stock']]);
  await importer.locator('.el-select__wrapper').click();await page.getByRole('option',{name:'Fasteners',exact:true}).click();
  const workbook=importer.getByLabel('Product import workbook',{exact:true});
  const setFile=async rows=>workbook.setInputFiles({name:'products.xlsx',mimeType:'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet',buffer:await workbookWithRows(rows)});
  await setFile(productRow(2,'Bad minimum',1,-1));await importer.getByRole('button',{name:'Preview import',exact:true}).click();
  await importer.getByText('Row 2: Use a nonnegative whole minimum stock.',{exact:true}).waitFor();
  assert.equal(await importer.getByRole('button',{name:'Confirm import',exact:true}).count(),0);
  assert.equal((await catalog.list()).products.length,2);
  await setFile(productRow(2,'Excel from UI',3.25,2));await importer.getByRole('button',{name:'Preview import',exact:true}).click();
  await importer.getByRole('button',{name:'Confirm import',exact:true}).waitFor();
  assert.equal((await catalog.list()).products.length,2);
  let commits=0;
  await page.route('**/api/products/import-commit?*',async route=>{commits++;const response=await route.fetch();assert.equal(response.status(),201);await route.abort('connectionreset');});
  await importer.getByRole('button',{name:'Confirm import',exact:true}).click();
  await importer.getByText('Import result is unconfirmed. Preview the file again to check existing products. Do not resubmit without a new preview.',{exact:true}).waitFor();
  assert.equal(commits,1);assert.equal((await catalog.list()).products.length,3);
  await page.unroute('**/api/products/import-commit?*');
  await importer.getByRole('button',{name:'Preview import',exact:true}).click();
  await importer.getByText('Row 2: This name already exists in the category or file.',{exact:true}).waitFor();
  assert.equal(await importer.getByRole('button',{name:'Confirm import',exact:true}).count(),0);
  assert.equal(commits,1);assert.equal((await catalog.list()).products.length,3);
  await importer.getByRole('button',{name:'Close import',exact:true}).click();
  await page.getByRole('button',{name:'Refresh',exact:true}).click();await page.getByText('Excel from UI',{exact:true}).waitFor();
  const added=(await catalog.list()).products.find(product=>product.name==='Excel from UI');assert.equal(added.quantity,0);
  const after=await catalog.detail(first.id);assert.equal(after.quantity,before.quantity);assert.equal(after.inventoryVersion,before.inventoryVersion);assert.equal(after.qrToken,before.qrToken);
  assert.deepEqual(errors,[]);
  console.log('Built RuoYi product assets: validated photo editing, decoded QR download, single/batch print, real Excel template, read-only preview and lost-commit duplicate protection passed.');
} finally {
  if(browser){await browser.browser.close();await browser.cleanup();}
  for(const instance of [proxy,server])if(instance){instance.closeAllConnections();await new Promise(resolve=>instance.close(resolve));}
  await pool.end();await rm(directory,{recursive:true,force:true});
}
